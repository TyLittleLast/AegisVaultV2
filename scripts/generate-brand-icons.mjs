/**
 * Emits `src/data/brandIcons.generated.ts` from the simple-icons SVGs.
 *
 * The package's main entry is a single 5 MB module with thousands of
 * non-annotated `let` declarations, so it cannot be tree-shaken: importing one
 * icon from it would ship the whole set. Reading the individual `.svg` files at
 * generation time keeps the runtime dependency at zero and the bundle at only
 * the brands listed in the manifest.
 *
 * Run with `npm run gen:brands` after editing the manifest or bumping the
 * package.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { BRAND_MANIFEST } from './brand-manifest.mjs'

const root = join(import.meta.dirname, '..')
const iconsDir = join(root, 'node_modules', 'simple-icons', 'icons')

/** slug -> official brand hex, recovered from the package index. */
function readHexBySlug() {
  const index = readFileSync(join(root, 'node_modules', 'simple-icons', 'index.mjs'), 'utf8')
  const hexes = new Map()
  const pattern = /slug:"([a-z0-9]+)"[\s\S]*?hex:"([0-9A-Fa-f]{6})"/g
  for (const match of index.matchAll(pattern)) hexes.set(match[1], match[2].toUpperCase())
  return hexes
}

function readMark(slug, hexes) {
  const hex = hexes.get(slug)
  if (!hex) throw new Error(`simple-icons n'expose pas de couleur pour « ${slug} »`)

  const svg = readFileSync(join(iconsDir, `${slug}.svg`), 'utf8')
  const viewBox = svg.match(/viewBox="([^"]+)"/)
  const path = svg.match(/<path d="([^"]+)"\s*\/?>/)
  if (!viewBox || !path) throw new Error(`SVG illisible pour « ${slug} »`)

  return { viewBox: viewBox[1], path: path[1], hex }
}

const hexes = readHexBySlug()
const marks = BRAND_MANIFEST.map(({ slug, aliases }) => ({
  slug,
  aliases,
  ...readMark(slug, hexes),
}))

const body = marks
  .map(
    ({ slug, viewBox, path, hex, aliases }) =>
      `  ${JSON.stringify(slug).padEnd(17)}: { hex: '${hex}', viewBox: '${viewBox}', aliases: [${aliases
        .map((a) => JSON.stringify(a))
        .join(', ')}], path: '${path}' },`,
  )
  .join('\n')

const file = `// Generated by scripts/generate-brand-icons.mjs — do not edit by hand.
// Source: simple-icons (CC0-1.0). Run \`npm run gen:brands\` to refresh.

export interface BrandMark {
  /** Official brand colour, uppercase hex without a leading '#'. */
  hex: string
  viewBox: string
  /** Lowercase names users type into the service field. */
  aliases: readonly string[]
  /** Single SVG path on a 24x24 grid unless viewBox says otherwise. */
  path: string
}

export const BRAND_MARKS: Record<string, BrandMark> = {
${body}
}
`

writeFileSync(join(root, 'src', 'data', 'brandIcons.generated.ts'), file, 'utf8')
console.log(`${marks.length} marques générées dans src/data/brandIcons.generated.ts`)
